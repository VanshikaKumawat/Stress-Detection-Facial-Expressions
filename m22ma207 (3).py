class SequenceAttentionLayer(tf.keras.layers.Layer):
    def __init__(self):
        super(SequenceAttentionLayer, self).__init__()

    def build(self, input_shape):
        self.attention_weight = self.add_weight(
            name="attention_weight",
            shape=(input_shape[-1], 1),
            initializer="random_normal",
            trainable=True
        )
        self.attention_bias = self.add_weight(
            name="attention_bias",
            shape=(input_shape[1], 1),
            initializer="zeros",
            trainable=True
        )

    def call(self, inputs):
        attention_logits = tf.nn.tanh(tf.tensordot(inputs, self.attention_weight, axes=1) + self.attention_bias)
        attention_weights = tf.nn.softmax(attention_logits, axis=1)
        weighted_sum = tf.reduce_sum(inputs * attention_weights, axis=1)
        return weighted_sum

# Full model architecture
def build_stress_detection_model(sequence_length=10, input_shape=(48, 48, 1)):
    sequence_input = Input(shape=(sequence_length, *input_shape))

    # Convert grayscale to RGB for compatibility with MobileNetV2
    def grayscale_to_rgb(batch_tensor):
        reshaped = tf.reshape(batch_tensor, (-1, 48, 48, 1))
        return tf.image.grayscale_to_rgb(reshaped)

    rgb_input = Lambda(grayscale_to_rgb)(sequence_input)

    # MobileNetV2 pretrained CNN encoder
    cnn_encoder = MobileNetV2(input_shape=(48, 48, 3), include_top=False, weights='imagenet')
    cnn_encoder.trainable = False
    features = cnn_encoder(rgb_input)
    pooled_features = GlobalAveragePooling2D()(features)

    # Reshape features to sequence format for ConvLSTM2D
    reshaped_sequence = Lambda(lambda x: tf.reshape(x, (-1, sequence_length, 1, 1280, 1)))(pooled_features)

    # Temporal modeling using ConvLSTM2D
    conv_lstm_output = ConvLSTM2D(filters=64, kernel_size=(1, 3), return_sequences=True)(reshaped_sequence)
    squeezed = Lambda(lambda x: tf.squeeze(x, axis=2))(conv_lstm_output)
    averaged_features = Lambda(lambda x: tf.reduce_mean(x, axis=2))(squeezed)

    # Apply temporal attention to focus on important frames
    context_vector = SequenceAttentionLayer()(averaged_features)

    # Fully connected classification layers
    x = Dropout(0.5)(context_vector)
    x = Dense(64, activation='relu')(x)
    x = Dropout(0.3)(x)
    output = Dense(1, activation='sigmoid')(x)

    return Model(sequence_input, output)

