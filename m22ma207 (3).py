def build_temporal_model_with_attention():
    # Define input with shape corresponding to a sequence of grayscale frames
    input_layer = Input(shape=(10, 48, 48, 1), name="input_layer")

    # Convert grayscale to 3-channel RGB format for MobileNetV2 compatibility
    rgb_input = Lambda(lambda x: tf.repeat(x, repeats=3, axis=-1))(input_layer)

    # Use MobileNetV2 as the feature extractor (frozen)
    backbone = MobileNetV2(input_shape=(48, 48, 3), include_top=False, weights='imagenet')
    backbone.trainable = False

    # Apply CNN backbone to each frame
    features = TimeDistributed(backbone)(rgb_input)
    features = TimeDistributed(GlobalAveragePooling2D())(features)

    # Prepare input format for ConvLSTM2D
    features = Lambda(lambda x: tf.expand_dims(x, axis=2))(features)
    features = Lambda(lambda x: tf.expand_dims(x, axis=-1))(features)

    # Capture temporal patterns using ConvLSTM2D
    x = ConvLSTM2D(64, kernel_size=(1, 3), padding='same', return_sequences=True)(features)
    x = Lambda(lambda x: tf.squeeze(x, axis=2))(x)
    x = Lambda(lambda x: tf.reduce_mean(x, axis=2))(x)

    # Apply temporal attention mechanism
    attention_output, attention_weights = TemporalAttention(return_attention=True, name="temporal_attention")(x)

    # Classification head
    x = Dropout(0.3)(attention_output)
    x = Dense(64, activation='relu')(x)
    x = Dropout(0.3)(x)
    output = Dense(1, activation='sigmoid')(x)

    # Construct and return the model
    return Model(inputs=input_layer, outputs=[output, attention_weights])

