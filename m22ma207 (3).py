def create_frame_sequences(data_loader, max_batches):
    sequences_X, sequences_y = [], []
    batch_counter = 0

    for images, labels in data_loader:
        for idx in range(0, len(images) - SEQUENCE_LENGTH + 1, SEQUENCE_LENGTH):
            sequence = images[idx:idx + SEQUENCE_LENGTH]
            if sequence.shape[0] == SEQUENCE_LENGTH:
                sequences_X.append(sequence)
                sequences_y.append(labels[idx])
        batch_counter += 1
        if batch_counter >= max_batches:
            break

    return np.array(sequences_X), np.array(sequences_y)

