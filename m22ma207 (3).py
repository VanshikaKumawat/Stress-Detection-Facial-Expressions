import tensorflow as tf
from tensorflow.keras.models import Model
from tensorflow.keras.layers import Input, Lambda, TimeDistributed, GlobalAveragePooling2D, ConvLSTM2D, Dropout, Dense
from tensorflow.keras.applications import MobileNetV2

# Define a custom layer for Temporal Attention
@tf.keras.utils.register_keras_serializable()
class TemporalAttention(tf.keras.layers.Layer):
    def __init__(self, return_attention=False, **kwargs):
        super(TemporalAttention, self).__init__(**kwargs)
        self.return_attention = return_attention

    def build(self, input_shape):
        # Initialize weights for attention mechanism
        self.W = self.add_weight(name="att_weight", shape=(input_shape[-1], 1),
                                 initializer="random_normal", trainable=True)
        self.b = self.add_weight(name="att_bias", shape=(input_shape[1], 1),
                                 initializer="zeros", trainable=True)

    def call(self, inputs):
        # Calculate attention scores
        e = tf.nn.tanh(tf.tensordot(inputs, self.W, axes=1) + self.b)
        alpha = tf.nn.softmax(e, axis=1)
        # Calculate context vector
        context = tf.reduce_sum(inputs * alpha, axis=1)
        if self.return_attention:
            return context, alpha
        return context

# Function to build the temporal model with attention
def build_temporal_model_with_attention():
    input_layer = Input(shape=(10, 48, 48, 1), name="input_layer")
    # Replicate input channels to match MobileNetV2 input shape
    x = Lambda(lambda x: tf.repeat(x, repeats=3, axis=-1))(input_layer)

    # Use MobileNetV2 as base model with pretrained weights
    base_cnn = MobileNetV2(input_shape=(48, 48, 3), include_top=False, weights='imagenet')
    base_cnn.trainable = False
    x = TimeDistributed(base_cnn)(x)
    x = TimeDistributed(GlobalAveragePooling2D())(x)

    # Apply ConvLSTM2D for sequential feature extraction
    x = Lambda(lambda x: tf.expand_dims(x, axis=2))(x)
    x = Lambda(lambda x: tf.expand_dims(x, axis=-1))(x)
    x = ConvLSTM2D(64, kernel_size=(1, 3), padding='same', return_sequences=True)(x)

    # Reduce sequence dimension and take average
    x = Lambda(lambda x: tf.squeeze(x, axis=2))(x)
    x = Lambda(lambda x: tf.reduce_mean(x, axis=2))(x)

    # Apply temporal attention
    context, alpha = TemporalAttention(return_attention=True, name="temporal_attention")(x)

    # Add dropout and dense layers for classification
    x = Dropout(0.3)(context)
    x = Dense(64, activation='relu')(x)
    x = Dropout(0.3)(x)
    output = Dense(1, activation='sigmoid')(x)

    return Model(inputs=input_layer, outputs=[output, alpha])

