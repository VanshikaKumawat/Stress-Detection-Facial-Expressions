def prepare_sequence_dataset(root_path, sequence_length=10):
    sequences = []
    labels = []

    category_map = {'non_stress': 0, 'stress': 1}

    for class_name, class_label in category_map.items():
        class_path = os.path.join(root_path, class_name)
        image_files = sorted(os.listdir(class_path))
        image_files = shuffle(image_files)

        for start_idx in range(0, len(image_files) - sequence_length + 1, sequence_length):
            sequence_frames = []
            for offset in range(sequence_length):
                image_path = os.path.join(class_path, image_files[start_idx + offset])
                image = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)
                resized_image = cv2.resize(image, (48, 48))
                normalized = resized_image / 255.0
                sequence_frames.append(normalized)
            sequences.append(sequence_frames)
            labels.append(class_label)

    return np.array(sequences)[..., np.newaxis], np.array(labels)

