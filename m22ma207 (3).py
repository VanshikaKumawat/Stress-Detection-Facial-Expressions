class SequenceAttentionLayer(tf.keras.layers.Layer):
    def __init__(self):
        super(SequenceAttentionLayer, self).__init__()

    def build(self, input_shape):
        feature_dim = input_shape[-1]
        time_steps = input_shape[1]

        # Learnable weight and bias for attention scoring
        self.attention_weights = self.add_weight(
            name="weights",
            shape=(feature_dim, 1),
            initializer="random_normal",
            trainable=True
        )
        self.attention_bias = self.add_weight(
            name="bias",
            shape=(time_steps, 1),
            initializer="zeros",
            trainable=True
        )

    def call(self, inputs):
        # inputs shape: (batch_size, time_steps, features)
        attention_logits = tf.nn.tanh(tf.tensordot(inputs, self.attention_weights, axes=1) + self.attention_bias)
        attention_scores = tf.nn.softmax(attention_logits, axis=1)
        attended_output = tf.reduce_sum(inputs * attention_scores, axis=1)
        return attended_output

